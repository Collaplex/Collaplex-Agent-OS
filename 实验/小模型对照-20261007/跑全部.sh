#!/bin/bash
# 小模型对照实验 —— 按顺序把四个臂跑完。随时可以 Ctrl-C / kill, 重跑会自动接着来。
cd /home/lou/桌面/collaplex_agent || exit 1
日志={H}/日志
mkdir -p "$日志"
跑() {
  echo "=== $(date '+%F %T') 开始 $* ==="
  .venv/bin/python 实验/小模型对照-20261007/跑实验.py "$@" 2>&1 | tee -a "$日志/总.log"
}
跑 --臂 C --遍 5 --哪 本地      # 一致性: 硬判据 12 题 × 5 遍
跑 --臂 A --哪 本地             # 单轮: 整题库 × 1
跑 --臂 B --轮 100 --哪 本地    # 连续: 同一会话 100 轮
跑 --臂 D --云上限 1.0 --哪 云端  # 云端对照(有硬额度闸, 超了就收手)
echo "=== $(date '+%F %T') 全部跑完 ==="
