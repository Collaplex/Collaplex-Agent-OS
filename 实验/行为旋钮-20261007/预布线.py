"""行为旋钮 · 预布线（先天反射弧）

★ 这份表**不依赖任何历史数据、不需要学习**——它就是"感受器 → 效应器"的初始连通。
学习只改「边有多粗」，不改「哪条边存在」（拓扑固定 = 预布线）。

三种感受器槽（感受器就按这个分组，先天定死）：
  ① 任务类   —— 从任务文本的关键词判出（手写关键词表，不学）
  ② 上一步结果 —— 成功 / 报错 / 拦截
  ③ 已被拦次数 —— 0 / 1 / ≥2

先天规则（人写的"反射"，三条）：
  · 任务类 X → 它的本命做法（一条一族的反射弧，权重最高）
  · 上一步被拦 → 压低"上一步那个做法"（别重复被拦的路）
  · 已被拦 ≥2 次 → 原路再压低一档（相当于"停手/换路"的反射）

产出：`预布线.json`（槽编号 + 边 + 权），供效应器循环当初值。
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

这里 = Path(__file__).parent

# ── 感受器槽编号：用一个独立号段，跟记忆库节点(0..294)不撞 ──────
槽起点 = 100000

# ① 任务类：关键词 → (类别名, 本命动作族)。★表的顺序就是优先级（更特在前）
任务类: list[tuple[str, list[str], str]] = [
    ("分区磁盘", ["分区", "磁盘", "df"], "查:磁盘"),
    ("内存", ["内存", "ram", "mem", "free"], "查:内存"),
    ("目录占用", ["占多大", "/tmp 占", "目录多大", "du"], "查:占用"),
    ("端口", ["端口", "在听", "监听"], "查:端口"),
    ("进程", ["进程", "pgrep"], "查:进程"),
    ("服务", ["服务", "systemd", "unit"], "查:服务"),
    ("日志", ["日志", "journal", "报错"], "查:日志"),
    ("硬件", ["cpu", "几核", "温度", "gpu", "硬件", "lscpu"], "查:硬件"),
    ("负载运行", ["负载", "跑多久", "uptime", "运行时间"], "查:系统"),
    ("时间", ["几点", "时间", "日期"], "查:时间"),
    ("内核", ["内核", "kernel", "uname"], "查:内核"),
    ("网络地址", ["ip", "网卡", "地址", "网络"], "网:本地"),
]

上一步槽 = {k: 槽起点 + 100 + i for i, k in enumerate(["成功", "报错", "拦截"])}
被拦次数槽 = {k: 槽起点 + 200 + i for i, k in enumerate(["0", "1", "多"])}


def 任务类号(名: str) -> int:
    for i, (n, _, _) in enumerate(任务类):
        if n == 名:
            return 槽起点 + i
    raise KeyError(名)


def 判任务类(任务: str) -> str | None:
    """按手写关键词表判任务属于哪一类（先天规则，零学习）。"""
    低 = 任务.lower()
    for 名, 词表, _ in 任务类:
        if any(w in 低 for w in 词表):
            return 名
    return None


def 本命族(名: str) -> str:
    for n, _, 族 in 任务类:
        if n == 名:
            return 族
    return ""


def 边表(族们: list[str], 学习率: float = 1.0) -> dict[str, Any]:
    """拼出预布线：感受器槽 → 效应器(动作族) 的初始权重。"""
    边: dict[str, float] = {}
    # 反射一：任务类 → 本命做法（最强）
    for 名, _, 族 in 任务类:
        if 族 in 族们:
            边[f"{任务类号(名)}|{族}"] = 3.0 * 学习率
    # 反射二 / 三：被拦之后压低原路（具体压哪个族要运行时才知道，所以这里只登记"负偏置"的强度）
    元 = {
        "槽起点": 槽起点,
        "任务类": [{"名": n, "槽": 任务类号(n), "本命族": f} for n, _, f in 任务类],
        "上一步槽": 上一步槽,
        "被拦次数槽": 被拦次数槽,
        "偏置": {
            "被拦_压原路": -2.0,        # 上一步被拦 → 上一步那个族扣这么多
            "被拦多_再压": -1.0,        # 已被拦 ≥2 次 → 再扣一档
            "被拦_换族加分": 0.5,       # 被拦之后，不是原路的族统一加分（鼓励换）
        },
    }
    return {"边": 边, "元": 元}


if __name__ == "__main__":
    import sys

    sys.path.insert(0, str(这里))
    族们 = ["查:磁盘", "查:内存", "查:占用", "查:端口", "查:进程", "查:服务", "查:日志", "查:硬件",
            "查:系统", "查:时间", "查:内核", "网:本地", "读:内核内存"]
    表 = 边表(族们)
    (这里 / "预布线.json").write_text(json.dumps(表, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"预布线：{len(表['边'])} 条本命反射 + {len(任务类)} 个任务类槽 + 3 个结果槽 + 3 个次数槽")
    print("按任务判类的自查（题目集里那 12 道）:")
    for t in ["根分区还剩多少", "内存还剩多少", "8789 端口有没有在听", "现在几点", "系统跑了多久、负载多少",
              "/tmp 占多大空间", "有几个进程在跑", "本机 IP 是多少", "CPU 几核", "内核版本",
              "有哪些服务在跑", "日志最后几条说了什么"]:
        类 = 判任务类(t)
        print(f"  {t:22s} → {类 or '（判不出）':8s} 本命做法 {本命族(类) if 类 else '—'}")
