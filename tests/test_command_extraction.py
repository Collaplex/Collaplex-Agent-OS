"""命令提取回归 —— 覆盖三种来源写法与三道约束（尾巴优先 / 复述不计 / 表格不计）。

存在的理由：提取过宽会**静默**执行错误命令，实测两次代价 ——
  ① 过程段复述被当作交班 → 同一命令重复执行（6 题 4 中招，共 27 次）；
  ② 资料块内文件名（`pyrightconfig.json` / `include` / `.py` 等）被连续提交执行 13 条。
本文件为该两道约束的固化回归，调整提取规则后须先跑通。
跑法: ./.venv/bin/python tests/test_command_extraction.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import exec_agent  # noqa: E402

通过 = 0
失败 = 0


def 查(说明: str, 原文: str, 该是: list[str]) -> None:
    global 通过, 失败
    拿到 = exec_agent.规则层提取命令(原文)
    if 拿到 == 该是:
        通过 += 1
        print(f"  通过  {说明}")
    else:
        失败 += 1
        print(f"  不过  {说明}\n        实得 {拿到}\n        预期 {该是}")


print("=" * 100)
print("命令提取回归 —— 仅取执行意图明确的写法")
print("=" * 100)

# 一、尾巴句为权威来源（正文 + 反引号）
查(
    "尾巴句声明执行 → 提取该命令",
    "我先看一眼磁盘: `df -h`\n\n这趟我去跑 df -h。",
    ["df -h"],
)
查(
    "尾巴句声明执行，命令含管道",
    "端口这事得问系统: `ss -ltnp | grep 8789`\n\n这趟我去跑 ss -ltnp | grep 8789。",
    ["ss -ltnp | grep 8789"],
)
查(
    "尾巴句声明执行，命令未加反引号 → 取'跑'之后的片段",
    "这趟我去跑 df -h。",
    ["df -h"],
)
查(
    "片段非命令形态（含'跑'但无命令记号）→ 不取",
    "这趟我去跑一下它的配置。",
    [],
)

# 二、约束一：尾巴句声明不执行 → 正文中的命令一律不计
查(
    "尾巴句声明不执行，正文中仍有命令 → 全部不取",
    "查到了, 根分区还剩 118G。\n\n# 过程\n我用的是 `df -h`。\n\n这趟不用跑，我说完就完。",
    [],
)

# 三、约束二：复述不计（"跑了 / 执行了"为既往动作陈述，非执行意图）
查(
    "过程段末尾为复述 → 不作为交班",
    "# 结论\n根分区还剩 118G。\n\n# 过程\n跑了 `df -h`。",
    [],
)
查(
    "尾巴句本身为复述 → 不计",
    "# 结论\n还剩 118G。\n\n跑了 `df -h`。",
    [],
)
查(
    "正文内'我跑了 X'的复述 → 不计",
    "我跑了 `df -h` 拿到数字。\n\n# 过程\n(略)",
    [],
)
查(
    "结论中的收尾语（'跑完了'）→ 不作为命令（'跑'之后的片段不构成命令形态）",
    "结论: 跑完了, 就这样。",
    [],
)

# 四、约束三：资料块内表格行与字段名不作为命令
查(
    "资料表格行（竖线 + 反引号）→ 全部不取",
    "| 处 | 是什么 | 状态 |\n|---|---|---|\n| 1 | `./.venv/bin/python skill/skill_search/main.py index` | 已跑 |\n\n# 过程\n(略)",
    [],
)
查(
    "正文罗列手册字段（往 `include` 加 `.py`）→ 无执行意图，不取",
    "往 `include` 加新 `.py`、`extraPaths` 加脚本路径。\n\n# 过程\n(略)",
    [],
)

# 五、无尾巴句时回正文检索：须带执行意图标记
查(
    "正文含执行意图 → 取",
    "我得先跑一下 `du -sh ~/桌面` 看看有多大。\n\n# 过程\n(略)",
    ["du -sh ~/桌面"],
)
查(
    "正文仅提及命令、无执行意图 → 不取",
    "清理这件事 `rm -rf` 太危险, 得先看清现状。\n\n# 过程\n(略)",
    [],
)

# 六、尾巴句被写成 markdown 标题时（实测会）
查(
    "尾巴句写成标题（# 这趟我去跑 X）→ 仍取",
    "我先看一眼磁盘: `df -h`\n\n# 这趟我去跑 df -h。",
    ["df -h"],
)
查(
    "尾巴句写成标题声明不执行 → 正文中的命令不计",
    "还剩 118G。\n\n# 过程\n用了 `df -h`。\n\n# 这趟不用跑，我说完就完。",
    [],
)

print()
print("=" * 100)
print(f"结果: {通过} 通过 / {失败} 失败")
print("=" * 100)
sys.exit(1 if 失败 else 0)
