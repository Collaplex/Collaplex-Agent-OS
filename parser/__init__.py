"""parser —— 模型原始产出 → 干净正文。

★ 单开可跑（不用起 web、不用起模型）：`./.venv/bin/python parser/selftest.py`

分两层，这就是全部的设计：

  ① 适配件（`parser/adapters/<家族>.py`）—— 只放**这家模型自己的习惯**。
     一家一个文件，各写各的，不共享可变状态、不靠调用顺序（这是"防玄学 bug"的那一半）。
  ② 外壳（`parser/shell.py`）—— 模型无关的最后一道：正文不许空、捞不回就端原文、
     一个字没有就明说。★ 没有适配件也能活（直接走它），这就是保险。

顺序是 ① → ②：先剥该族的壳，再过通用兜底。**适配件把文本弄成什么样，② 都兜得住。**

填什么模型就加载谁：`config/parsing.json` 里按**关键词**匹配家族（别名/量化版换了照样命中），
命中不了 → 只走外壳。加一个模型 = 加一个适配件文件 ＋ `适配件/__init__.py` 里登记一行。
"""

from __future__ import annotations

from dataclasses import dataclass

from parser import shell as 外壳
from parser.adapters import 登记, 找家族


@dataclass(frozen=True)
class 结果:
    """一轮产出的解析结果。"""

    正文: str
    说明: str  # 非空 = 走了兜底/特化，调用方该把这句话报给界面或终端
    走了: str  # 走了哪条路（可观测：按模型统计兜底率就靠它）
    家族: str  # 命中的适配件家族；"" = 没命中，只走了外壳


def 取干净(原文: str, 模型: str = "") -> 结果:
    """模型原始产出 → 干净正文。

    ★ 不管走哪条路，返回的正文都不许因为"算出来是空"而把内容丢掉 ——
      除了"模型真一个字都没吐"那种情况（那时说明里会讲清楚）。
    """
    家族 = 找家族(模型)
    净 = 原文
    说明 = ""
    走了 = "外壳"
    if 家族:
        净, 说明 = 登记[家族].特化(原文)
        走了 = f"{家族}.特化 → 外壳"
    正文, 兜底说明 = 外壳.捞正文(净)
    if 兜底说明:
        说明 = 兜底说明
        走了 = f"{走了}（兜底）"
    return 结果(正文=正文, 说明=说明, 走了=走了, 家族=家族)


